#include<stdio.h>
int main()
{
   int a,b;
   scanf("%d",&a);
   scanf("%d",&b);
   printf("first integer:%d\n",a);//23
   printf("second integer:%d\n",b);//20
   printf("%d\n",a<b);//0
   printf("%d\n",a>b);//1
   printf("%d\n",a<=b);//0
   printf("%d\n",a>=b);//1
   printf("%d\n",a==b);//0
   printf("%d\n",a!=b);//1
   return 0;
}
